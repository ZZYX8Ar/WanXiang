        /// <summary>每只异兽的剧情碎片总数。</summary>
        public const int FragmentTotal = 6;

        public sealed class Entry
        {
            public string Material;      // 专属材料名（与异兽相关、30 个互不相同）
            public LoreFragment[] Frags; // 恰好 6 片
        }

        private static readonly Dictionary<string, Entry> Map = Build();

        public static bool HasEntry(string beastId)
            => !string.IsNullOrEmpty(beastId) && Map.ContainsKey(beastId);

        public static int Count => Map.Count;

        /// <summary>该异兽的专属材料名（无内容时返回空串）。</summary>
        public static string MaterialName(string beastId)
            => !string.IsNullOrEmpty(beastId) && Map.TryGetValue(beastId, out var e) ? e.Material : "";

        /// <summary>第 index 片（0 起）；越界或未收藏返回空。</summary>
        public static LoreFragment Fragment(string beastId, int index)
        {
            if (string.IsNullOrEmpty(beastId) || !Map.TryGetValue(beastId, out var e)) return default;
            if (e.Frags == null || index < 0 || index >= e.Frags.Length) return default;
            return e.Frags[index];
        }

        /// <summary>碎片显示名：「句芒的剧情碎片1」。</summary>
        public static string FragmentName(string beastDisplayName, int index)
            => beastDisplayName + "的剧情碎片" + (index + 1);

